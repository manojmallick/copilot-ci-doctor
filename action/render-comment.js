/**
 * Turns the JSON printed by `copilot-ci-doctor analyze --json` into the
 * Markdown body of a pull request comment. Used by action.yml; has no
 * dependencies so the action does not need an install step.
 */

export const MARKER = "<!-- copilot-ci-doctor -->";

const clean = (s) => String(s ?? "").replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim();

export function renderComment(result) {
  const lines = [MARKER, "### 🩺 copilot-ci-doctor", ""];

  if (!result || result.ok !== true) {
    lines.push("The diagnosis could not be completed.", "");
    lines.push("```", clean(result?.error || "No output from copilot-ci-doctor."), "```");
    return lines.join("\n") + "\n";
  }

  const run = result.run || {};
  const where = run.url ? `[${clean(run.workflow) || "workflow"} #${run.runId}](${run.url})` : `run ${run.runId}`;
  lines.push(`Failed run: ${where} on \`${clean(run.branch)}\``, "");

  const hyps = Array.isArray(result.hypotheses) ? result.hypotheses : [];
  if (hyps.length === 0) {
    lines.push("No root-cause hypotheses were returned.");
  } else {
    lines.push("| # | Likely cause | Confidence | Evidence |", "|--:|---|--:|---|");
    for (const h of hyps) {
      lines.push(`| ${h.rank ?? ""} | ${clean(h.title)} | ${Number(h.confidence) || 0}% | ${(h.evidence_refs || []).map(clean).join(", ")} |`);
    }
    const top = hyps[0];
    if (top?.explanation) lines.push("", `**Top hypothesis:** ${clean(top.explanation)}`);
  }

  lines.push(
    "",
    "<sub>Generated by a language model from redacted logs. Treat it as a lead, not a verdict. Run `copilot-ci-doctor fix --dry-run` locally to preview a patch.</sub>"
  );
  return lines.join("\n") + "\n";
}

// CLI: node render-comment.js result.json > comment.md
if (import.meta.url === `file://${process.argv[1]}`) {
  const fs = await import("node:fs");
  let result = null;
  try { result = JSON.parse(fs.readFileSync(process.argv[2], "utf8")); } catch { /* rendered as an error */ }
  process.stdout.write(renderComment(result));
}
