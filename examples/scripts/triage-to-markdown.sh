#!/bin/sh
# Write the diagnosis of a failed run to a Markdown file, for an issue, a chat message or a job summary.
#
#   examples/scripts/triage-to-markdown.sh triage.md
#   RUN_ID=1234567890 REPO=octocat/hello-world examples/scripts/triage-to-markdown.sh triage.md
#
# Works on any repository you can read (REPO), without a clone.
# Needs: copilot-ci-doctor and jq on the PATH.

set -u

file="${1:-triage.md}"

set --
[ -n "${RUN_ID:-}" ] && set -- "$@" --run-id "$RUN_ID"
[ -n "${REPO:-}" ] && set -- "$@" --repo "$REPO"

out=$(mktemp) || exit 1
trap 'rm -f "$out"' EXIT

if ! copilot-ci-doctor analyze --json "$@" > "$out" 2> /dev/null; then
  echo "analyze failed: $(jq -r '.error // "unknown error"' "$out")" >&2
  exit 1
fi

jq -r '"## CI failure: \(.run.workflow) #\(.run.runId)\n",
       "Branch `\(.run.branch)` · [run](\(.run.url))\n",
       "| # | Likely cause | Confidence | Evidence |",
       "|--:|---|--:|---|",
       (.hypotheses[] | "| \(.rank) | \(.title) | \(.confidence)% | \(.evidence_refs | join(", ")) |"),
       "\n_Generated by a language model from redacted logs; treat it as a lead._"' "$out" > "$file"

echo "Wrote $file"
